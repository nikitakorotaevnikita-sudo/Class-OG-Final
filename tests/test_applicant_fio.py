"""ФИО заявителя — того, ОТ КОГО обращение, а не любого упомянутого человека.

Требование аналитика: обращение приходит пачкой — сопроводительное письмо, тело
обращения и приложения (протоколы собраний, списки подписей, служебные записки).
В такой пачке фамилий много, и почти все они чужие: председатель собрания,
секретарь, руководитель организации, должностное лицо, которому адресовано
обращение, десятки подписавшихся.

Правила:

1. заявитель — лицо, ОТ КОТОРОГО обращение: шапка «от кого», глагол первого лица
   «я обращаюсь», контактное лицо для ответа; у коллективного — первый в списке;
2. искать сначала в сопроводительном письме («направляем обращение ФИО»), затем
   в шапке обращения;
3. подписанта протокола или списка подписей брать нельзя, пока он не подтверждён
   как заявитель в основном тексте.

Тексты здесь синтетические: реальные обращения содержат персональные данные.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent / "src"))

import pytest

from fio_extractor import extract_applicant_fio


# ── Где искать заявителя ────────────────────────────────────────────────────

def test_cover_letter_names_the_applicant():
    """Сопроводительное письмо — первый по приоритету источник."""
    text = (
        "Департамент по работе с обращениями граждан\n"
        "Направляем для рассмотрения обращение Петровой Марии Ивановны "
        "по вопросу ремонта дороги.\n"
        "Исполнитель: Соколов А.А., тел. 8-999-000-00-00\n"
    )
    assert extract_applicant_fio(text) == "Петрова Мария Ивановна"


def test_header_of_the_appeal():
    text = (
        "Главе администрации города N\n"
        "от Иванова Ивана Ивановича,\n"
        "проживающего по адресу: ул. Ленина, д. 5\n\n"
        "Прошу отремонтировать дорогу."
    )
    assert extract_applicant_fio(text) == "Иванов Иван Иванович"


def test_first_person_statement():
    text = "Я, Сидоров Пётр Петрович, обращаюсь по вопросу вывоза мусора."
    assert extract_applicant_fio(text) == "Сидоров Пётр Петрович"


def test_contact_person_for_the_answer():
    text = (
        "Обращение от инициативной группы жителей микрорайона.\n"
        "Контактное лицо для ответа: Смирнов Олег Викторович."
    )
    assert extract_applicant_fio(text) == "Смирнов Олег Викторович"


def test_collective_appeal_takes_the_first_signature():
    text = (
        "Коллективное обращение жителей дома 5 по улице Ленина.\n"
        "Просим отремонтировать кровлю.\n"
        "Подписи:\n"
        "1. Кузнецова Анна Сергеевна\n"
        "2. Морозов Дмитрий Олегович\n"
        "3. Волкова Елена Петровна\n"
    )
    assert extract_applicant_fio(text) == "Кузнецова Анна Сергеевна"


def test_cover_letter_wins_over_the_header_of_an_attachment():
    """Порядок источников: сопроводительное письмо важнее всего остального."""
    text = (
        "Направляем обращение Петровой Марии Ивановны.\n\n"
        "Приложение: протокол общего собрания.\n"
        "Председатель собрания Орлов Олег Олегович\n"
        "Секретарь Белова Нина Ивановна\n"
    )
    assert extract_applicant_fio(text) == "Петрова Мария Ивановна"


# ── Кого заявителем считать нельзя ──────────────────────────────────────────

def test_protocol_signatory_is_not_the_applicant():
    text = (
        "Главе администрации города N\n"
        "от Иванова Ивана Ивановича\n\n"
        "Прошу рассмотреть вопрос о ремонте кровли.\n"
        "Приложение: протокол общего собрания собственников.\n"
        "Председатель собрания Орлов Олег Олегович\n"
    )
    assert extract_applicant_fio(text) == "Иванов Иван Иванович"


def test_addressee_is_not_the_applicant():
    """«Главе города Петрову П.П.» — адресат, а не заявитель."""
    text = "Главе города Петрову Петру Петровичу. Прошу убрать свалку у дома 7."
    assert extract_applicant_fio(text) is None


def test_organisation_head_in_the_body_is_not_the_applicant():
    text = (
        "В обращении говорится, что директор управляющей компании "
        "Кузьмин Артём Сергеевич не отвечает на заявки жильцов."
    )
    assert extract_applicant_fio(text) is None


def test_nothing_to_take_gives_none():
    text = "Во дворе дома 7 не убирают снег уже неделю."
    assert extract_applicant_fio(text) is None


# ── Подсказка модели ────────────────────────────────────────────────────────

def test_model_hint_is_used_when_the_name_is_in_the_text():
    """Модель видит структуру документа лучше правил — но врать ей не даём."""
    text = (
        "Сопроводительное письмо к обращению.\n"
        "Обращение поступило в отношении Николаева Николая Николаевича "
        "от его соседки Фёдоровой Ольги Ивановны.\n"
    )
    assert extract_applicant_fio(text, llm_hint="Фёдорова Ольга Ивановна") == \
        "Фёдорова Ольга Ивановна"


def test_hallucinated_hint_is_ignored():
    text = "Я, Сидоров Пётр Петрович, обращаюсь по вопросу вывоза мусора."
    assert extract_applicant_fio(text, llm_hint="Выдуманов Иван Иванович") == \
        "Сидоров Пётр Петрович"


def test_hint_pointing_at_a_protocol_signatory_is_rejected():
    """Типичная ошибка модели: взять подписанта приложения."""
    text = (
        "Главе администрации города N\n"
        "от Иванова Ивана Ивановича\n\n"
        "Приложение: протокол общего собрания.\n"
        "Председатель собрания Орлов Олег Олегович\n"
    )
    assert extract_applicant_fio(text, llm_hint="Орлов Олег Олегович") == \
        "Иванов Иван Иванович"


def test_signatory_confirmed_as_applicant_is_accepted():
    """Если тот же человек в шапке — подписант он или нет, уже неважно."""
    text = (
        "От Орлова Олега Олеговича.\n"
        "Прошу рассмотреть обращение.\n"
        "Приложение: протокол собрания.\n"
        "Председатель собрания Орлов Олег Олегович\n"
    )
    assert extract_applicant_fio(text, llm_hint="Орлов Олег Олегович") == \
        "Орлов Олег Олегович"


# ── Падеж: в шапке ФИО почти всегда в родительном ───────────────────────────

@pytest.mark.parametrize("text,expected", [
    ("от Иванова Ивана Ивановича", "Иванов Иван Иванович"),
    ("от Петровой Марии Ивановны", "Петрова Мария Ивановна"),
    ("от Кузнецова Сергея Петровича", "Кузнецов Сергей Петрович"),
    ("Заявитель: Соколова Анна Дмитриевна", "Соколова Анна Дмитриевна"),
])
def test_genitive_header_is_returned_in_nominative(text, expected):
    assert extract_applicant_fio(f"Главе города\n{text}\nПрошу помочь.") == expected


def test_initials_in_the_header_are_kept():
    text = "Главе города\nот Иванова И.И.\nПрошу помочь."
    assert extract_applicant_fio(text) == "Иванов И.И."


# ── Ничего не ломаем в старом поведении ─────────────────────────────────────

def test_empty_input():
    assert extract_applicant_fio("") is None
    assert extract_applicant_fio(None) is None
    assert extract_applicant_fio(None, llm_hint="Иванов Иван Иванович") is None
