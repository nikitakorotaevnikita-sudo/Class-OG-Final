"""Протоколы хранилищ."""

from __future__ import annotations

from typing import Optional, Protocol, Sequence

import numpy as np

from datetime import datetime

from .models import AppealResult, ClassifierEntry, Job, ModelVersion


class DuplicateError(ValueError):
    """Запись с таким ключом уже есть (memory и PostgreSQL бросают одинаково).

    Наследует ValueError: прежние вызовы, ловившие ValueError, работают как раньше.
    """


class ClassifierStore(Protocol):
    def upsert_entries(self, entries: list[ClassifierEntry]) -> int: ...
    def load_entries(self) -> list[ClassifierEntry]: ...
    def count_entries(self) -> int: ...
    def add_vectors(
        self, version: int, rows: list[tuple[str, str, str, Optional[np.ndarray]]]
    ) -> int: ...
    def search(
        self, query: np.ndarray, version: int, top_k: int, include_annotations: bool
    ) -> list[tuple[str, float]]: ...
    def pending_annotations(self, version: int) -> list[tuple[int, str]]: ...
    def vector_text(self, vector_id: int) -> Optional[str]: ...
    def set_embedding(self, vector_id: int, embedding: np.ndarray) -> None: ...
    def add_annotation(self, code: str, text: str, version: int) -> int: ...
    def annotations_for(self, code: str) -> list[str]: ...
    def delete_annotations(self, code: str, text_prefix: Optional[str] = None) -> int: ...
    def annotations_by_code(self) -> dict[str, list[str]]: ...
    def annotated_codes(self) -> list[str]: ...
    def vectors_for_version(self, version: int) -> list[tuple[str, str, str]]: ...


class ModelStore(Protocol):
    def register(self, mv: ModelVersion) -> None: ...
    def register_new(self, mv: ModelVersion) -> None: ...  # ModelVersionExists, если занята
    def active(self) -> Optional[ModelVersion]: ...
    def get(self, version: int) -> Optional[ModelVersion]: ...
    def list(self) -> list[ModelVersion]: ...
    def activate(self, version: int) -> None: ...
    def next_version(self) -> int: ...


class AppealStore(Protocol):
    def create(
        self,
        appeal_text: str,
        document_id: Optional[int] = None,
        ip_address: Optional[str] = None,
        appeal_id: Optional[str] = None,
        created_at: Optional[datetime] = None,
        conn=None,
    ) -> str: ...
    def save_result(self, appeal_id: str, result: AppealResult, conn=None) -> None: ...
    def get_text(self, appeal_id: str) -> Optional[str]: ...
    def set_verification(
        self,
        appeal_id: str,
        status: str,
        operator_codes: Optional[list[str]],
        comment: Optional[str],
        verified_by: Optional[str] = None,
        verified_at: Optional[datetime] = None,
        conn=None,
    ) -> bool: ...
    def as_log_entries(self, statuses: Optional[tuple[str, ...]] = None) -> list[dict]: ...
    def stats(self) -> dict: ...
    def backoffice_stats(self, days: int = 30) -> dict: ...
    def log_llm_request(
        self,
        appeal_id: Optional[str],
        success: bool,
        attempt: int,
        elapsed: Optional[float],
        confidence: Optional[float],
        error: Optional[str],
        candidates_count: int,
        created_at: Optional[datetime] = None,
    ) -> None: ...
    def ip_addresses(self, appeal_ids: list[str]) -> dict[str, Optional[str]]: ...
    def llm_log_count(self) -> int: ...
    def set_request_meta(
        self, appeal_id: str, ip_address: Optional[str], elapsed_seconds: Optional[float],
        only_missing: bool = False,
    ) -> None: ...


class HistoricalStore(Protocol):
    def add(self, records: list[dict], source_file: str) -> int: ...
    def count(self) -> int: ...
    def all(self) -> list[dict]: ...


class MetaStore(Protocol):
    def get(self, key: str) -> Optional[str]: ...
    def set(self, key: str, value: str) -> None: ...


class JobStore(Protocol):
    def create(
        self,
        job_type: str,
        payload: dict,
        appeal_id: Optional[str] = None,
        document_id: Optional[int] = None,
        webhook_url: Optional[str] = None,
        max_queued: Optional[int] = None,
        queue_class: str = "classify",
    ) -> Job: ...
    def get(self, job_id: str) -> Optional[Job]: ...
    def claim(self, job_id: str) -> Optional[Job]: ...
    def lock_owned(self, job_id: str, attempts: int, conn=None) -> bool: ...
    def finish(
        self, job_id: str, result: Optional[dict], error: Optional[str], conn=None,
        attempts: Optional[int] = None,
    ) -> bool: ...
    def position(self, job_id: str) -> Optional[int]: ...
    def list(self, limit: int = 50, job_type: Optional[str] = None) -> list[Job]: ...
    def stats(self, job_type: Optional[str] = None) -> dict: ...
    def latest(self, job_type: str) -> Optional[Job]: ...
    def has_active(self, job_type: str) -> bool: ...
    def cleanup_expired(
        self, ttl_hours: float, delivered_grace_sec: Optional[float] = None,
    ) -> int: ...
    def import_job(self, job: Job) -> None: ...
    # --- очередь в таблице jobs ---
    def claim_next(
        self, queues: Sequence[str], worker_id: str, lease_sec: float,
    ) -> Optional[Job]: ...
    def fail_lost_training(self) -> list[Job]: ...
    def extend_lease(self, job_id: str, attempts: int, lease_sec: float) -> bool: ...
    def release_for_retry(
        self, job_id: str, attempts: int, delay_sec: float, error: str,
    ) -> bool: ...
    def mark_delivered(self, job_id: str) -> None: ...
    def delete(self, job_id: str) -> None: ...
    def live_workers(self, queue: str) -> list[str]: ...
